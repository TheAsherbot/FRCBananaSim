/**
 * @file FlywheelComponent.h
 * @brief Component representing a high-RPM rotational flywheel with 1D semi-implicit integration and chassis recoil.
 */

#pragma once

#include "Core/ECS/Core/Entity.h"
#include "Actuation/DCMotorModel.h"
#include <string>
#include <cstdint>
#include <glm/vec3.hpp>

namespace FRCBananaSim::Robot::Mechanisms::Components
{
    /**
     * @struct FlywheelComponent
     * @brief ECS component holding flywheel inertia, drive motor parameters, and recoil attachment.
     */
    struct FlywheelComponent
    {
        std::string name;

        // Kinematic Hierarchy & Recoil Binding
        Core::ECS::Core::Entity parentEntity = Core::ECS::Core::invalidEntity; ///< Parent shooter / chassis entity receiving recoil torque.
        Core::ECS::Core::Entity visualEntity = Core::ECS::Core::invalidEntity; ///< Visual mesh entity rotated in RenderUpdate.

        // Actuation & Transmission
        Actuation::DCMotorModel motorModel;
        uint32_t motorCount = 1;
        double gearRatio = 1.0;                 ///< Overall reduction ratio G = omega_motor / omega_flywheel.
        double efficiency = 0.98;               ///< Gearbox and bearing mechanical efficiency (0.0 to 1.0).

        // Inertias (kg*m^2)
        double flywheelInertiaKgm2 = 0.003;     ///< Flywheel disc rotational inertia J_disc (kg*m^2).
        double rollerInertiaKgm2 = 0.0;         ///< Additional roller rotational inertia J_rollers (kg*m^2).
        double rollerRatio = 1.0;               ///< Roller speed ratio rho_roller = omega_roller / omega_flywheel.
        double reflectedRotorInertiaKgm2 = 0.0; ///< Reflected motor rotor inertia N * J_rotor * G^2 (kg*m^2).
        double totalRotationalInertiaKgm2 = 0.0;///< Total lumped inertia J_total = J_disc + J_rollers*rho^2 + J_refl.

        // Geometry & Spin Axis
        glm::vec3 spinAxis = { 0.0f, 0.0f, 1.0f };          ///< Direction of flywheel rotation in parent link body frame.
        glm::vec3 visualLocalOffset = { 0.0f, 0.06f, 0.06f }; ///< Local mounting offset of visualEntity relative to parentEntity.

        // Friction & External Load
        double coulombFrictionNm = 0.02;        ///< Bearing Coulomb friction torque (N*m).
        double viscousDampingNms = 0.0001;      ///< Bearing viscous damping (N*m*s/rad).
        double externalLoadTorqueNm = 0.0;      ///< External disturbance torque (e.g. ball compression) in N*m.
        double statorCurrentLimitA = 80.0;      ///< Stator current clamp threshold (A).
        bool brakeMode = false;                 ///< Coast mode (false) by default for shooters.

        // Integration Settings
        uint32_t subSteps = 4;                  ///< Number of internal sub-steps per 200 Hz tick (default 4 = 1.25 ms).

        // Runtime State
        double angularPositionRad = 0.0;        ///< Total accumulated angular position theta_fw in radians.
        double angularVelocityRadPerSec = 0.0;  ///< Current rotational velocity omega_fw in rad/s.
        double angularVelocityRpm = 0.0;        ///< Current rotational velocity in RPM.

        // Runtime Command Demands
        double commandedVoltage = 0.0;          ///< Motor drive command in Volts (-12.0V to +12.0V).
        double appliedVoltage = 0.0;            ///< Actual applied motor voltage.
        double motorTorqueNm = 0.0;             ///< Net torque generated by motor (N*m).
        double statorCurrentA = 0.0;            ///< Instantaneous motor current (A).
        double recoilTorqueNm = 0.0;            ///< Reaction torque applied to parent body (N*m).

        // Control Slot Mapping
        std::vector<uint32_t> motorSlots = { 10 }; ///< All SimInputs/SimOutputs motor slot indices for this mechanism.

        /**
         * @brief Gets the primary (leader) control slot index.
         * @return Primary motor slot index, or 0 if empty.
         */
        uint32_t GetPrimaryMotorSlot() const { return motorSlots.empty() ? 0 : motorSlots[0]; }
    };
}